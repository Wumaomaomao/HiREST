import json
import logging
import os
from typing import Any, Dict, List
import copy
from hirest.model.operation import Operation
from hirest.parser.preparser.preprocess import Preprocess
from hirest.parser.process_llm_dep import get_swagger_understanding_m
from hirest.parser.process_llm_serv import get_swagger_understanding_service
from hirest.parser.process_llm_und import get_swagger_understanding_s
from hirest.parser.process_parameter import give_param_type

from hirest.utils.RW_data import load_data, write_data

logger = logging.getLogger(__name__)

class OpenAPIParser:
    """OpenAPIParser class is responsible for parsing OpenAPI specification files (swagger2.0/3.0, json/yaml) into operation sildes."""
    
    
    def __init__(
            self,
            file_path: str
        ):
        """
        Constructor for OpenAPIParser class.

        Parameter
        ----------
        preprocessed_data : dict
            The data is processed by oasparser and LLM, have mixed dependencies and url, method,... information.
        """
        self.file_path = file_path
        self.service_knowledge = None
        self.llm_for_sisp_swagger_understanding = None
        self.llm_for_misp_swagger_understanding = None
        self.op_slides: List[Operation] = []
        self.llm_dependencies = None

        self.preprocess_manager = Preprocess(self.file_path)
        # preprocess_data = Preprocess(self.file_path)
        self.preprocessed_data: dict = self.preprocess_manager.run()# the first version parse data.
        self.preprocessed_data_file_data_no_ref = self.preprocess_manager.file_data_no_ref
        
    
    def extract_service_knowledge(self):
        """
        enhance service semantic understanding globally.
        """ 
        #25.5.16 update, add service knowledge generated by llm.
        self.service_knowledge : str = get_swagger_understanding_service(
            data = self.preprocess_manager.file_data_no_ref
        )
        logger.info(f"Service knowledge extracted:{self.service_knowledge}")


    def extract_parameter_constraints(self):
        """
        Extract parameter constraints from the OpenAPI specification.
        """
        self.llm_for_sisp_swagger_understanding: list = get_swagger_understanding_s(
            data = self.preprocess_manager.file_data_no_ref,
            service_knowl = self.service_knowledge
        )

        logger.info(f"Parameter constraints extracted:{self.llm_for_sisp_swagger_understanding}")
    
    def extract_api_dependencies(self):
        """
        Extract API dependencies from the OpenAPI specification.
        """
        self.llm_for_misp_swagger_understanding: dict = get_swagger_understanding_m(
            data = self.preprocess_manager.file_data_no_ref
        )
        logger.info(f"API dependencies extracted:{self.llm_for_misp_swagger_understanding}")
        self.llm_dependencies = self.llm_for_misp_swagger_understanding

    def gen_operation_slides(self):
        """
        Generate operation slides from the OpenAPI specification.
        """
        self.op_slides = self.parse_op_slides()
        # logger.info(f"Operation slides generated: {len(self.op_slides)} slides created.")

    def save_op_slides(self, save_file_path: str):
        output_dir = os.path.dirname(save_file_path)
        os.makedirs(output_dir, exist_ok=True)
        with open(save_file_path, "w", encoding="utf-8") as f:
            json.dump([op.model_dump() for op in self.op_slides], f, indent=4, ensure_ascii=False)

    def parse_op_slides(self) -> List[Operation]:
        """
        Parse the OpenAPI specification file into operation slides.
        """
        operation_model_results = []

        # 切片
        file_data = load_data(self.file_path)
        slides = self.slice_swagger(file_data)

        for path, methods in file_data.get("paths", {}).items():
            for method, details in methods.items():
                if method.lower() not in ["get", "post", "put", "delete", "patch", "head", "options"]:
                    continue
                operation = Operation(
                    method = method,
                    url = path,
                    param_list = give_param_type(self.preprocessed_data, path, method),
                    raw_doc_slide = next(
                        (op for op in slides if op["path"] == path and op["method"].lower() == method.lower()),
                        None
                    ),
                    dependencies = (
                        (self.llm_dependencies or {})
                        .get(path, {})
                        .get(method.lower(), {})
                        .get("all-dependencies", [])
                    )
                )
                operation_model_results.append(operation)


        return operation_model_results

    def resolve_ref(self, ref: str, root: Dict[str, Any], ref_cache: Dict[str, Any]) -> Dict[str, Any]:
        """
        Resolve a $ref with caching to avoid repeated parsing.

        Parameters:
        - ref: the $ref string like '#/components/parameters/UserId'
        - root: the root OpenAPI spec dictionary
        - ref_cache: a dictionary to cache resolved refs

        Returns:
        - The resolved dict for the $ref
        """
        if ref in ref_cache:
            return copy.deepcopy(ref_cache[ref])  # 防止引用对象被修改

        parts = ref.lstrip("#/").split("/")
        result = root
        for part in parts:
            result = result[part]

        ref_cache[ref] = result
        return copy.deepcopy(result)

    def resolve_refs_in_schema(self, schema: Dict[str, Any], spec: Dict[str, Any], ref_cache: Dict[str, Any]) -> Dict[str, Any]:
        if "$ref" in schema:
            return self.resolve_refs_in_schema(self.resolve_ref(schema["$ref"], spec, ref_cache), spec, ref_cache)

        if schema.get("type") == "object" and "properties" in schema:
            for prop_name, prop_schema in schema["properties"].items():
                schema["properties"][prop_name] = self.resolve_refs_in_schema(prop_schema, spec, ref_cache)

        if schema.get("type") == "array" and "items" in schema:
            schema["items"] = self.resolve_refs_in_schema(schema["items"], spec, ref_cache)

        # 支持组合结构递归解析
        for keyword in ["allOf", "anyOf", "oneOf"]:
            if keyword in schema and isinstance(schema[keyword], list):
                schema[keyword] = [
                    self.resolve_refs_in_schema(sub_schema, spec, ref_cache)
                    for sub_schema in schema[keyword]
                ]

        return schema

    def slice_swagger(self, spec: Dict[str, Any]) -> List[Dict[str, Any]]:
        """
        Slice Swagger spec into individual endpoint + method slices.

        Parameters:
        - spec: Swagger/OpenAPI full spec

        Returns:
        - List of operation slices (dicts)
        """
        operations = []
        ref_cache = {}

        for path, methods in spec.get("paths", {}).items():
            for method, operation in methods.items():
                if method.lower() not in ["get", "post", "put", "delete", "patch", "head", "options"]:
                    continue
                operation_slice = {
                    "method": method.upper(),
                    "path": path,
                    "summary": operation.get("summary"),
                    "description": operation.get("description"),
                    "parameters": [],
                    "requestBody": {},
                    "responses": operation.get("responses"),
                    "operationId": operation.get("operationId")
                }

                # ---------- 解析参数 ----------
                parameters = operation.get("parameters", [])
                for param in parameters:
                    if "$ref" in param:
                        resolved_param = self.resolve_ref(param["$ref"], spec, ref_cache)
                        # 若 resolved_param 中还有 schema 且 schema 中存在 $ref，则进一步解析
                        schema = resolved_param.get("schema")
                        if schema and "$ref" in schema:
                            resolved_param["schema"] = self.resolve_ref(schema["$ref"], spec, ref_cache)
                        operation_slice["parameters"].append(resolved_param)
                    else:
                        # 若 param 中 schema 有 $ref，也解析
                        schema = param.get("schema")
                        if schema and "$ref" in schema:
                            param["schema"] = self.resolve_ref(schema["$ref"], spec, ref_cache)
                        operation_slice["parameters"].append(param)

                # ---------- 解析请求体 ----------
                request_body = operation.get("requestBody")
                if request_body:
                    if "$ref" in request_body:
                        resolved_body = self.resolve_ref(request_body["$ref"], spec, ref_cache)
                        operation_slice["requestBody"] = resolved_body
                    else:
                        resolved_body = copy.deepcopy(request_body)
                        content = resolved_body.get("content", {})
                        for media_type, media_obj in content.items():
                            schema = media_obj.get("schema")
                            if schema:
                                media_obj["schema"] = self.resolve_refs_in_schema(schema, spec, ref_cache)
                        operation_slice["requestBody"] = resolved_body

                operations.append(operation_slice)

        return operations


